    "import pandas as pd\n",
    "from rdkit import Chem\n",
    "from rdkit.Chem import Descriptors\n",
    "import logging\n",
    "\n",
    "logging.basicConfig(level=logging.INFO, format=\"%(asctime)s [%(levelname)s] %(message)s\")\n",
    "logger = logging.getLogger(__name__)\n",
    "\n",
    "class DataCurator:\n",
    "    \"\"\"Module for molecular data curation, standardization, and property calculation using RDKit.\"\"\"\n",
    "    \n",
    "    def __init__(self, df: pd.DataFrame, activity_threshold_nM: float = 1000.0):\n",
    "        self.df = df.copy()\n",
    "        self.activity_threshold_nM = activity_threshold_nM\n",
    "\n",
    "    def clean_and_standardize(self) -> pd.DataFrame:\n",
    "        \"\"\"Performs data cleaning, smiles sanitization, duplicates removal, and binarization.\"\"\"\n",
    "        if self.df.empty:\n",
    "            logger.warning(\"DataFrame is empty. Skipping curation.\")\n",
    "            return self.df\n",
    "\n",
    "        initial_count = len(self.df)\n",
    "        logger.info(f\"Starting data curation on {initial_count} records...\")\n",
    "\n",
    "        # 1. Drop rows with missing values in critical columns\n",
    "        self.df.dropna(subset=[\"molecule_chembl_id\", \"canonical_smiles\", \"standard_value\"], inplace=True)\n",
    "\n",
    "        # 2. Convert standard_value to numeric\n",
    "        self.df[\"standard_value\"] = pd.to_numeric(self.df[\"standard_value\"], errors=\"coerce\")\n",
    "        self.df.dropna(subset=[\"standard_value\"], inplace=True)\n",
    "\n",
    "        # 3. Canonicalize SMILES and filter out invalid molecules using RDKit\n",
    "        valid_smiles = []\n",
    "        canonical_smiles_list = []\n",
    "        \n",
    "        for smiles in self.df[\"canonical_smiles\"]:\n",
    "            mol = Chem.MolFromSmiles(smiles)\n",
    "            if mol is not None:\n",
    "                canonical_smiles_list.append(Chem.MolToSmiles(mol))\n",
    "                valid_smiles.append(True)\n",
    "            else:\n",
    "                valid_smiles.append(False)\n",
    "\n",
    "        self.df[\"valid_smiles\"] = valid_smiles\n",
    "        self.df = self.df[self.df[\"valid_smiles\"] == True].drop(columns=[\"valid_smiles\"])\n",
    "        self.df[\"canonical_smiles\"] = canonical_smiles_list\n",
    "\n",
    "        # 4. Remove duplicates (keep the median value if multiple entries exist for the same molecule)\n",
    "        self.df = self.df.groupby([\"molecule_chembl_id\", \"canonical_smiles\"], as_index=False)[\"standard_value\"].median()\n",
    "\n",
    "        # 5. Calculate Molecular Weight using RDKit for quality check\n",
    "        self.df[\"molecular_weight\"] = self.df[\"canonical_smiles\"].apply(\n",
    "            lambda s: Descriptors.MolWt(Chem.MolFromSmiles(s))\n",
    "        )\n",
    "\n",
    "        # 6. Define binary activity label (1 = Active based on threshold, 0 = Inactive)\n",
    "        # Assuming standard_value represents IC50 in nM (lower is more active)\n",
    "        self.df[\"active\"] = (self.df[\"standard_value\"] <= self.activity_threshold_nM).astype(int)\n",
    "\n",
    "        final_count = len(self.df)\n",
    "        logger.info(f\"Curation complete. Retained {final_count} high-quality unique compounds (dropped {initial_count - final_count} records).\")\n",
    "        \n",
    "        return self.df"
